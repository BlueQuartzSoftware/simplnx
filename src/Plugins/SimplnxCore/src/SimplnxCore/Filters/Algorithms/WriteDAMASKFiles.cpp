WriteDAMASKFiles::WriteDAMASKFiles(DataStructure& dataStructure, const IFilter::MessageHandler& messageHandler, const std::atomic_bool& shouldCancel, WriteDAMASKFilesInputValues* inputValues)
: m_DataStructure(dataStructure)
, m_InputValues(inputValues)
, m_ShouldCancel(shouldCancel)
, m_MessageHandler(messageHandler)
{
}

WriteDAMASKFiles::~WriteDAMASKFiles() noexcept = default;

Result<> WriteDAMASKFiles::operator()()
{
  const auto& imageGeom = m_DataStructure.getDataRefAs<ImageGeom>(m_InputValues->ImageGeometryPath);
  const auto& featureIds = m_DataStructure.getDataRefAs<Int32Array>(m_InputValues->FeatureIdsArrayPath).getDataStoreRef();
  const auto& cellEulerAngles = m_DataStructure.getDataRefAs<Float32Array>(m_InputValues->CellEulerAnglesArrayPath).getDataStoreRef();
  const auto& cellPhases = m_DataStructure.getDataRefAs<Int32Array>(m_InputValues->CellPhasesArrayPath).getDataStoreRef();
  const auto dimensions = imageGeom.getDimensions();
  const usize cellsPerSlice = dimensions[0] * dimensions[1];
  MessageHelper messageHelper(m_MessageHandler);

  int32 maxGrainId = 0;
  GrainData grainData;
  if(m_InputValues->DataFormat == 1)
  {
    ThrottledMessenger maximumMessenger = messageHelper.createThrottledMessenger();
    for(usize z = 0; z < dimensions[2]; z++)
    {
      if(m_ShouldCancel)
      {
        return {};
      }
      const usize sliceStart = z * cellsPerSlice;
      const usize sliceEnd = sliceStart + cellsPerSlice;
      for(usize cellIndex = sliceStart; cellIndex < sliceEnd; cellIndex++)
      {
        const int32 featureId = featureIds[cellIndex];
        maxGrainId = std::max(maxGrainId, featureId);
      }
      SendProgress(maximumMessenger, "Finding Maximum Grain ID", z + 1, dimensions[2]);
    }

    if(maxGrainId <= 0)
    {
      return MakeErrorResult(
          -12074, fmt::format("The feature IDs array '{}' has no positive feature IDs. Grainwise DAMASK output requires at least one grain.", m_InputValues->FeatureIdsArrayPath.toString()));
    }

    const usize grainCount = static_cast<usize>(maxGrainId);
    grainData.Phases.resize(grainCount + 1, 0);
    grainData.Orientations.resize(grainCount + 1, {0.0F, 0.0F, 0.0F});
    grainData.HasCells.resize(grainCount + 1, false);

    // The direct-indexed buckets use 16 bytes per grain for phase and orientation. Presence flags use one bit per grain, with no per-cell temporary storage.
    ThrottledMessenger bucketMessenger = messageHelper.createThrottledMessenger();
    for(usize z = 0; z < dimensions[2]; z++)
    {
      if(m_ShouldCancel)
      {
        return {};
      }
      const usize sliceStart = z * cellsPerSlice;
      const usize sliceEnd = sliceStart + cellsPerSlice;
      for(usize cellIndex = sliceStart; cellIndex < sliceEnd; cellIndex++)
      {
        const int32 featureId = featureIds[cellIndex];
        if(featureId > 0)
        {
          const usize grainId = static_cast<usize>(featureId);
          grainData.HasCells[grainId] = true;
          grainData.Phases[grainId] = cellPhases[cellIndex];
          grainData.Orientations[grainId] = {cellEulerAngles[cellIndex * 3], cellEulerAngles[cellIndex * 3 + 1], cellEulerAngles[cellIndex * 3 + 2]};
        }
      }
      SendProgress(bucketMessenger, "Bucketing Grain Data", z + 1, dimensions[2]);
    }

    const usize emptyGrainCount = static_cast<usize>(std::count(grainData.HasCells.cbegin() + 1, grainData.HasCells.cend(), false));
    if(emptyGrainCount > 0)
    {
      m_MessageHandler(IFilter::Message::Type::Warning, fmt::format("{} grain{} in [1, {}] {} no cells. Phase 0 and zero Euler angles were written for the missing grain data.", emptyGrainCount,
                                                                    emptyGrainCount == 1 ? "" : "s", maxGrainId, emptyGrainCount == 1 ? "has" : "have"));
    }
  }

  const usize microstructureCount = m_InputValues->DataFormat == 0 ? imageGeom.getNumberOfCells() : static_cast<usize>(maxGrainId);
  const std::array<fs::path, 2> fileList = {m_InputValues->OutputPath / fmt::format("{}.geom", m_InputValues->GeometryFileName), m_InputValues->OutputPath / "material.config"};
  std::vector<Result<AtomicFile>> files;
  files.reserve(fileList.size());
  for(const auto& outputPath : fileList)
  {
    files.push_back(AtomicFile::Create(outputPath));
    if(files.back().invalid())
    {
      RemoveTemporaryFiles(files);
      return ConvertResult(std::move(files.back()));
    }
  }

  const auto writeFile = [&](FileIndex fileIndex, std::string_view progressMessage, auto&& writer) -> Result<> {
    if(m_ShouldCancel)
    {
      RemoveTemporaryFiles(files);
      return {};
    }

    messageHelper.sendMessage(std::string(progressMessage));
    const usize index = ToIndex(fileIndex);
    const fs::path tempPath = files[index].value().tempFilePath();
    const WriteStatus status = writer(tempPath);
    if(status == WriteStatus::Cancelled || m_ShouldCancel)
    {
      RemoveTemporaryFiles(files);
      return {};
    }
    if(status == WriteStatus::OpenError)
    {
      RemoveTemporaryFiles(files);
      return MakeErrorResult(-12075, fmt::format("Could not open '{}' for writing (target '{}').", tempPath.string(), fileList[index].string()));
    }
    if(status == WriteStatus::WriteError)
    {
      RemoveTemporaryFiles(files);
      return MakeErrorResult(-12076, fmt::format("Writing to '{}' failed (target '{}'). Check available disk space.", tempPath.string(), fileList[index].string()));
    }
    return {};
  };

  Result<> writeResult = writeFile(FileIndex::Geometry, "Writing Geometry File (File 1/2)...",
                                   [&](const fs::path& path) { return WriteGeometryFile(path, imageGeom, featureIds, *m_InputValues, microstructureCount, m_ShouldCancel, messageHelper); });
  if(writeResult.invalid())
  {
    return writeResult;
  }

  writeResult = writeFile(FileIndex::Material, "Writing Material Configuration (File 2/2)...",
                          [&](const fs::path& path) { return WriteMaterialFile(path, imageGeom, cellEulerAngles, cellPhases, *m_InputValues, grainData, m_ShouldCancel, messageHelper); });
  if(writeResult.invalid())
  {
    return writeResult;
  }

  if(m_ShouldCancel)
  {
    RemoveTemporaryFiles(files);
    return {};
  }

  for(auto& file : files)
  {
    Result<> commitResult = file.value().commit();
    if(commitResult.invalid())
    {
      RemoveTemporaryFiles(files);
      return commitResult;
    }
  }
  return {};
}
