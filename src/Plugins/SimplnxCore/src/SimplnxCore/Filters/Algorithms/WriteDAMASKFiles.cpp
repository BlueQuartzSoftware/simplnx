enum class WriteStatus
{
  Success,
  Cancelled,
  OpenError,
  WriteError
};

enum class FileIndex : usize
{
  Geometry = 0,
  Material = 1
};

struct GrainData
{
  std::vector<int32> Phases;
  std::vector<std::array<float32, 3>> Orientations;
  std::vector<bool> HasCells;
};

constexpr usize ToIndex(FileIndex fileIndex)
{
  return static_cast<usize>(fileIndex);
}

WriteStatus FlushBuffer(std::ostream& output, fmt::memory_buffer& buffer)
{
  output.write(buffer.data(), static_cast<std::streamsize>(buffer.size()));
  buffer.clear();
  return output ? WriteStatus::Success : WriteStatus::WriteError;
}

WriteStatus CloseOutput(std::ofstream& output)
{
  output.close();
  return output ? WriteStatus::Success : WriteStatus::WriteError;
}

void SendProgress(ThrottledMessenger& messenger, std::string_view label, usize current, usize total)
{
  messenger.sendThrottledMessage([=]() { return fmt::format("{}: {:.0f}%", label, CalculatePercentComplete(current, total)); });
}

void WriteGeometryHeader(fmt::memory_buffer& buffer, const ImageGeom& imageGeom, int32 homogenizationIndex, usize microstructureCount)
{
  const auto dimensions = imageGeom.getDimensions();
  const auto spacing = imageGeom.getSpacing();
  const auto origin = imageGeom.getOrigin();
  const std::array<float32, 3> size = {static_cast<float32>(dimensions[0]) * spacing[0], static_cast<float32>(dimensions[1]) * spacing[1], static_cast<float32>(dimensions[2]) * spacing[2]};

  fmt::format_to(std::back_inserter(buffer), "6       header\n");
  fmt::format_to(std::back_inserter(buffer), "# Generated by DREAM.3D\n");
  fmt::format_to(std::back_inserter(buffer), "grid    a {}    b {}    c {}\n", dimensions[0], dimensions[1], dimensions[2]);
  fmt::format_to(std::back_inserter(buffer), "size    x {:.3f}    y {:.3f}    z {:.3f}\n", size[0], size[1], size[2]);
  fmt::format_to(std::back_inserter(buffer), "origin    x {:.3f}    y {:.3f}    z {:.3f}\n", origin[0], origin[1], origin[2]);
  fmt::format_to(std::back_inserter(buffer), "homogenization  {}\n", homogenizationIndex);
  fmt::format_to(std::back_inserter(buffer), "microstructures {}\n", microstructureCount);
}

WriteStatus WriteGeometryFile(const fs::path& filePath, const ImageGeom& imageGeom, const AbstractDataStore<int32>& featureIds, const WriteDAMASKFilesInputValues& inputValues,
                              usize microstructureCount, const std::atomic_bool& shouldCancel, MessageHelper& messageHelper)
{
  std::ofstream output(filePath, std::ios::binary);
  if(!output.is_open())
  {
    return WriteStatus::OpenError;
  }

  fmt::memory_buffer buffer;
  WriteGeometryHeader(buffer, imageGeom, inputValues.HomogenizationIndex, microstructureCount);
  const usize cellCount = imageGeom.getNumberOfCells();
  if(inputValues.DataFormat == 0 && inputValues.CompressGeomFile)
  {
    if(shouldCancel)
    {
      return WriteStatus::Cancelled;
    }
    fmt::format_to(std::back_inserter(buffer), "1 to {:10d}", cellCount);
    if(FlushBuffer(output, buffer) == WriteStatus::WriteError)
    {
      return WriteStatus::WriteError;
    }
    return CloseOutput(output);
  }

  const auto dimensions = imageGeom.getDimensions();
  const usize cellsPerSlice = dimensions[0] * dimensions[1];
  usize entriesPerLine = 0;
  ThrottledMessenger progressMessenger = messageHelper.createThrottledMessenger();
  for(usize z = 0; z < dimensions[2]; z++)
  {
    if(shouldCancel)
    {
      return WriteStatus::Cancelled;
    }

    const usize sliceStart = z * cellsPerSlice;
    const usize sliceEnd = sliceStart + cellsPerSlice;
    for(usize cellIndex = sliceStart; cellIndex < sliceEnd; cellIndex++)
    {
      if(entriesPerLine != 0)
      {
        // This modulo check mirrors the legacy counter for parity.
        if(entriesPerLine % dimensions[0] != 0)
        {
          fmt::format_to(std::back_inserter(buffer), " ");
        }
        else
        {
          fmt::format_to(std::back_inserter(buffer), "\n");
          entriesPerLine = 0;
        }
      }

      const int64 value = inputValues.DataFormat == 0 ? static_cast<int64>(cellIndex + 1) : static_cast<int64>(featureIds[cellIndex]);
      fmt::format_to(std::back_inserter(buffer), "{:10d}", value);
      entriesPerLine++;
    }

    if(FlushBuffer(output, buffer) == WriteStatus::WriteError)
    {
      return WriteStatus::WriteError;
    }
    SendProgress(progressMessenger, "Writing Geometry File (File 1/2)", z + 1, dimensions[2]);
  }

  if(buffer.size() != 0 && FlushBuffer(output, buffer) == WriteStatus::WriteError)
  {
    return WriteStatus::WriteError;
  }
  return CloseOutput(output);
}

void WriteMaterialHeader(fmt::memory_buffer& buffer)
{
  fmt::format_to(std::back_inserter(buffer), "#############################################################################\n");
  fmt::format_to(std::back_inserter(buffer), "# Generated by DREAM.3D\n");
  fmt::format_to(std::back_inserter(buffer), "#############################################################################\n");
  fmt::format_to(std::back_inserter(buffer), "# Add <homogenization>, <crystallite>, and <phase> for a complete definition\n");
  fmt::format_to(std::back_inserter(buffer), "#############################################################################\n");
}

void WriteTexture(fmt::memory_buffer& buffer, std::string_view label, usize index, const std::array<float32, 3>& orientation)
{
  constexpr float64 k_RadiansToDegrees = 180.0 / std::numbers::pi;
  const float64 phi1 = static_cast<float64>(orientation[0]) * k_RadiansToDegrees;
  const float64 phi = static_cast<float64>(orientation[1]) * k_RadiansToDegrees;
  const float64 phi2 = static_cast<float64>(orientation[2]) * k_RadiansToDegrees;
  fmt::format_to(std::back_inserter(buffer), "[{}{}]\n", label, index);
  fmt::format_to(std::back_inserter(buffer), "(gauss) phi1 {:.3f}   Phi {:.3f}    phi2 {:.3f}   scatter 0.0   fraction 1.0 \n", phi1, phi, phi2);
}

void WriteMicrostructure(fmt::memory_buffer& buffer, std::string_view label, usize index, int32 phase)
{
  fmt::format_to(std::back_inserter(buffer), "[{}{}]\n", label, index);
  fmt::format_to(std::back_inserter(buffer), "crystallite 1\n");
  fmt::format_to(std::back_inserter(buffer), "(constituent)   phase {} texture {} fraction 1.0\n", phase, index);
}

WriteStatus WritePointwiseMaterial(std::ofstream& output, fmt::memory_buffer& buffer, const ImageGeom& imageGeom, const AbstractDataStore<float32>& cellEulerAngles,
                                   const AbstractDataStore<int32>& cellPhases, const std::atomic_bool& shouldCancel, MessageHelper& messageHelper)
{
  const auto dimensions = imageGeom.getDimensions();
  const usize cellsPerSlice = dimensions[0] * dimensions[1];
  const usize progressTotal = dimensions[2] * 2;
  ThrottledMessenger progressMessenger = messageHelper.createThrottledMessenger();

  fmt::format_to(std::back_inserter(buffer), "<texture>\n");
  for(usize z = 0; z < dimensions[2]; z++)
  {
    if(shouldCancel)
    {
      return WriteStatus::Cancelled;
    }
    const usize sliceStart = z * cellsPerSlice;
    const usize sliceEnd = sliceStart + cellsPerSlice;
    for(usize cellIndex = sliceStart; cellIndex < sliceEnd; cellIndex++)
    {
      const std::array<float32, 3> orientation = {cellEulerAngles[cellIndex * 3], cellEulerAngles[cellIndex * 3 + 1], cellEulerAngles[cellIndex * 3 + 2]};
      WriteTexture(buffer, "point", cellIndex + 1, orientation);
    }
    if(FlushBuffer(output, buffer) == WriteStatus::WriteError)
    {
      return WriteStatus::WriteError;
    }
    SendProgress(progressMessenger, "Writing Material Configuration (File 2/2)", z + 1, progressTotal);
  }

  fmt::format_to(std::back_inserter(buffer), "<microstructure>\n");
  for(usize z = 0; z < dimensions[2]; z++)
  {
    if(shouldCancel)
    {
      return WriteStatus::Cancelled;
    }
    const usize sliceStart = z * cellsPerSlice;
    const usize sliceEnd = sliceStart + cellsPerSlice;
    for(usize cellIndex = sliceStart; cellIndex < sliceEnd; cellIndex++)
    {
      WriteMicrostructure(buffer, "point", cellIndex + 1, cellPhases[cellIndex]);
    }
    if(FlushBuffer(output, buffer) == WriteStatus::WriteError)
    {
      return WriteStatus::WriteError;
    }
    SendProgress(progressMessenger, "Writing Material Configuration (File 2/2)", dimensions[2] + z + 1, progressTotal);
  }
  return WriteStatus::Success;
}

WriteStatus WriteGrainwiseMaterial(std::ofstream& output, fmt::memory_buffer& buffer, const GrainData& grainData, const std::atomic_bool& shouldCancel, MessageHelper& messageHelper)
{
  const usize grainCount = grainData.Phases.size() - 1;
  const usize progressTotal = grainCount * 2;
  ThrottledMessenger progressMessenger = messageHelper.createThrottledMessenger();

  fmt::format_to(std::back_inserter(buffer), "<texture>\n");
  for(usize grainId = 1; grainId <= grainCount; grainId++)
  {
    if(shouldCancel)
    {
      return WriteStatus::Cancelled;
    }
    WriteTexture(buffer, "grain", grainId, grainData.Orientations[grainId]);
    if(FlushBuffer(output, buffer) == WriteStatus::WriteError)
    {
      return WriteStatus::WriteError;
    }
    SendProgress(progressMessenger, "Writing Material Configuration (File 2/2)", grainId, progressTotal);
  }

  fmt::format_to(std::back_inserter(buffer), "<microstructure>\n");
  for(usize grainId = 1; grainId <= grainCount; grainId++)
  {
    if(shouldCancel)
    {
      return WriteStatus::Cancelled;
    }
    WriteMicrostructure(buffer, "grain", grainId, grainData.Phases[grainId]);
    if(FlushBuffer(output, buffer) == WriteStatus::WriteError)
    {
      return WriteStatus::WriteError;
    }
    SendProgress(progressMessenger, "Writing Material Configuration (File 2/2)", grainCount + grainId, progressTotal);
  }
  return WriteStatus::Success;
}

WriteStatus WriteMaterialFile(const fs::path& filePath, const ImageGeom& imageGeom, const AbstractDataStore<float32>& cellEulerAngles, const AbstractDataStore<int32>& cellPhases,
                              const WriteDAMASKFilesInputValues& inputValues, const GrainData& grainData, const std::atomic_bool& shouldCancel, MessageHelper& messageHelper)
{
  std::ofstream output(filePath, std::ios::binary);
  if(!output.is_open())
  {
    return WriteStatus::OpenError;
  }

  fmt::memory_buffer buffer;
  WriteMaterialHeader(buffer);
  const WriteStatus status = inputValues.DataFormat == 0 ? WritePointwiseMaterial(output, buffer, imageGeom, cellEulerAngles, cellPhases, shouldCancel, messageHelper) :
                                                           WriteGrainwiseMaterial(output, buffer, grainData, shouldCancel, messageHelper);
  if(status != WriteStatus::Success)
  {
    return status;
  }
  if(buffer.size() != 0 && FlushBuffer(output, buffer) == WriteStatus::WriteError)
  {
    return WriteStatus::WriteError;
  }
  return CloseOutput(output);
}

void RemoveTemporaryFiles(const std::vector<Result<AtomicFile>>& files)
{
  for(const auto& file : files)
  {
    if(file.valid())
    {
      file.value().removeTempFile();
    }
  }
}
