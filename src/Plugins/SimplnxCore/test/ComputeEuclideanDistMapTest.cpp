// V&V fixture harness (Class 1 analytical + Class 4 invariant)
//
// SEMANTICS WARNING -- finding ED-1. The float32 output of this filter is NOT a Euclidean
// distance transform. It is the straight-line distance from each cell to *the one particular
// seed cell that the breadth-first propagation happened to hand it*, and that seed is chosen by
// a tie-break, not by proximity. The propagation loop
// (Algorithms/ComputeEuclideanDistMap.cpp:185-200) assigns
//     voxel_NearestNeighbor[i] = voxel_NearestNeighbor[neighpoint]
// UNCONDITIONALLY inside a j = 0..5 loop over the offsets
//     { -nx*ny, -nx, -1, +1, +nx, +nx*ny }  ==  { -z, -y, -x, +x, +y, +z },
// so the LAST qualifying neighbour wins and the descending priority is
//
//     +z  >  +y  >  +x  >  -x  >  -y  >  -z
//
// The consequence is asserted below and is load-bearing: in fixture A, cell 0 gets
// gbEuclidean == 4.0 even though a boundary seed exists 2.0 away. See the ED-1 comment on
// fixture A in the generated table.
// ============================================================================================

