// Brute-force physical distance from every cell to the NEAREST seed, where the seed set is taken
// from the filter's own Manhattan output (a cell is a seed exactly when its Manhattan distance is
// 0). This is the Class 4 floor for the euclidean map and is computed here, in the test, from
// filter output plus geometry alone -- it does not consult the oracle table.
std::vector<float64> TrueEdt(const Fixture& fixture, const std::vector<int32>& manhattan)
{
  const int64 nX = static_cast<int64>(fixture.dims[0]);
  const int64 nY = static_cast<int64>(fixture.dims[1]);
  const int64 nZ = static_cast<int64>(fixture.dims[2]);
  std::vector<std::array<int64, 3>> seeds;
  for(int64 i = 0; i < static_cast<int64>(manhattan.size()); i++)
  {
    if(manhattan[i] == 0)
    {
      seeds.push_back({i % nX, (i / nX) % nY, i / (nX * nY)});
    }
  }
  std::vector<float64> out(manhattan.size(), -1.0);
  if(seeds.empty())
  {
    return out;
  }
  for(int64 i = 0; i < static_cast<int64>(manhattan.size()); i++)
  {
    if(fixture.featureIds[static_cast<usize>(i)] <= 0)
    {
      continue;
    }
    const int64 x = i % nX;
    const int64 y = (i / nX) % nY;
    const int64 z = i / (nX * nY);
    float64 best = std::numeric_limits<float64>::max();
    for(const auto& seed : seeds)
    {
      const float64 dX = static_cast<float64>(x - seed[0]) * static_cast<float64>(fixture.spacing[0]);
      const float64 dY = static_cast<float64>(y - seed[1]) * static_cast<float64>(fixture.spacing[1]);
      const float64 dZ = static_cast<float64>(z - seed[2]) * static_cast<float64>(fixture.spacing[2]);
      best = std::min(best, std::sqrt((dX * dX) + (dY * dY) + (dZ * dZ)));
    }
    out[static_cast<usize>(i)] = best;
  }
  return out;
}
