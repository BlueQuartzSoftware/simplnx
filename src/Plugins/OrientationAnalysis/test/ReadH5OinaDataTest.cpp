// Error propagation from the trusted EbsdLib boundary at header-read time: a
// phase group missing its Lattice Angles dataset is reported through -9582, and
// the message carries the file path and scan name.
//
// The header of every selected scan is read at preflight, from two different
// return sites: the first selected scan's read and the per-scan loop's read. Both
// are pinned here, and each section asserts the scan name its own site injects.
