//------------------------------------------------------------------------------
// Toy .h5oina fixture description. Written out in full, the dataset set below is
// exactly the minimum H5OINAReader requires: the four Header scalars, one or more
// Phases/<n> groups carrying Phase Name / Lattice Dimensions / Lattice Angles /
// Laue Group / Space Group, and the nine Data datasets it reads unconditionally.
// The root Manufacturer / Software Version / Index datasets are written for
// realism only -- the reader never reads them.
//
// The guard fixtures deliberately depart from that minimum: `omitBandsDataset`
// and `omitLatticeAngles` drop a required dataset outright, and `groupName`
// overrides the phase index that the group name carries. The remaining guard
// fixtures keep the full dataset set but give it values a well formed file would
// not have.
//------------------------------------------------------------------------------
struct PhaseSpec
{
  std::string name;
  int32 laueGroup = k_LaueCubicHigh;
  int32 spaceGroup = 225;
  std::array<float32, 3> latticeDimensions = {1.0F, 1.0F, 1.0F};
  // Lattice angles as an H5OINA file stores them: RADIANS.
  std::array<float32, 3> latticeAngles = {1.5707964F, 1.5707964F, 1.5707964F};
  // Group name override; empty means "use the phase's 1-based position".
  std::string groupName;
  bool omitLatticeAngles = false;
};

struct ScanSpec
{
  std::string name = "1";
  int32 xCells = 1;
  int32 yCells = 1;
  float32 xStep = 1.0F;
  float32 yStep = 1.0F;
  std::vector<PhaseSpec> phases;
  std::vector<uint8> phase;
  std::vector<uint8> bandContrast;
  std::vector<uint8> bandSlope;
  std::vector<uint8> bands;
  std::vector<uint8> error;
  std::vector<float32> euler; // 3 components per point, interleaved
  std::vector<float32> mad;
  std::vector<float32> x;
  std::vector<float32> y;
  // Guard-fixture switches.
  bool omitBandsDataset = false;
};

//------------------------------------------------------------------------------
template <typename T>
void WriteVector(hid_t gid, const std::string& name, const std::vector<hsize_t>& dims, const std::vector<T>& data)
{
  const herr_t err = H5Lite::writeVectorDataset<T>(gid, name, dims, data);
  REQUIRE(err >= 0);
}

//------------------------------------------------------------------------------
hid_t OpenOrCreateGroup(hid_t fileId, const std::string& path)
{
  const hid_t err = H5Utilities::createGroupsFromPath(path, fileId);
  REQUIRE(err >= 0);
  const hid_t gid = H5Gopen(fileId, path.c_str(), H5P_DEFAULT);
  REQUIRE(gid >= 0);
  return gid;
}

//------------------------------------------------------------------------------
// Writes the fixture to <binary test output dir>/<fileName> and returns the path.
//------------------------------------------------------------------------------
fs::path WriteH5OinaFixture(const std::string& fileName, const std::vector<ScanSpec>& scans, bool writeFormatVersion = true, const std::string& formatVersion = "5.0")
{
  const fs::path filePath = fs::path(unit_test::k_BinaryTestOutputDir.view()) / fileName;
  const hid_t fileId = H5Fcreate(filePath.string().c_str(), H5F_ACC_TRUNC, H5P_DEFAULT, H5P_DEFAULT);
  REQUIRE(fileId >= 0);

  if(writeFormatVersion)
  {
    REQUIRE(H5Lite::writeStringDataset(fileId, ebsdlib::H5OINA::FormatVersion, formatVersion) >= 0);
  }
  // Inert realism -- the reader never reads these three.
  REQUIRE(H5Lite::writeStringDataset(fileId, ebsdlib::H5OINA::Manufacturer, "Oxford Instruments") >= 0);
  REQUIRE(H5Lite::writeStringDataset(fileId, ebsdlib::H5OINA::SoftwareVersion, "V&V toy fixture") >= 0);
  REQUIRE(H5Lite::writeStringDataset(fileId, ebsdlib::H5OINA::Index, "1") >= 0);

  for(const ScanSpec& scan : scans)
  {
    const std::string headerPath = fmt::format("{}/{}/{}", scan.name, ebsdlib::H5OINA::EBSD, ebsdlib::H5OINA::Header);
    const hid_t headerGid = OpenOrCreateGroup(fileId, headerPath);
    REQUIRE(H5Lite::writeScalarDataset<int32>(headerGid, ebsdlib::H5OINA::XCells, scan.xCells) >= 0);
    REQUIRE(H5Lite::writeScalarDataset<int32>(headerGid, ebsdlib::H5OINA::YCells, scan.yCells) >= 0);
    REQUIRE(H5Lite::writeScalarDataset<float32>(headerGid, ebsdlib::H5OINA::XStep, scan.xStep) >= 0);
    REQUIRE(H5Lite::writeScalarDataset<float32>(headerGid, ebsdlib::H5OINA::YStep, scan.yStep) >= 0);

    for(usize i = 0; i < scan.phases.size(); i++)
    {
      const PhaseSpec& phaseSpec = scan.phases[i];
      const std::string groupName = phaseSpec.groupName.empty() ? std::to_string(i + 1) : phaseSpec.groupName;
      const hid_t phaseGid = OpenOrCreateGroup(fileId, fmt::format("{}/{}/{}", headerPath, ebsdlib::H5OINA::Phases, groupName));
      REQUIRE(H5Lite::writeStringDataset(phaseGid, ebsdlib::H5OINA::PhaseName, phaseSpec.name) >= 0);
      WriteVector<float32>(phaseGid, ebsdlib::H5OINA::LatticeDimensions, {1, 3}, {phaseSpec.latticeDimensions[0], phaseSpec.latticeDimensions[1], phaseSpec.latticeDimensions[2]});
      if(!phaseSpec.omitLatticeAngles)
      {
        WriteVector<float32>(phaseGid, ebsdlib::H5OINA::LatticeAngles, {1, 3}, {phaseSpec.latticeAngles[0], phaseSpec.latticeAngles[1], phaseSpec.latticeAngles[2]});
      }
      REQUIRE(H5Lite::writeScalarDataset<int32>(phaseGid, ebsdlib::H5OINA::LaueGroup, phaseSpec.laueGroup) >= 0);
      REQUIRE(H5Lite::writeScalarDataset<int32>(phaseGid, ebsdlib::H5OINA::SpaceGroup, phaseSpec.spaceGroup) >= 0);
      REQUIRE(H5Gclose(phaseGid) >= 0);
    }
    REQUIRE(H5Gclose(headerGid) >= 0);

    const hid_t dataGid = OpenOrCreateGroup(fileId, fmt::format("{}/{}/{}", scan.name, ebsdlib::H5OINA::EBSD, ebsdlib::H5OINA::Data));
    const auto pointCount = static_cast<hsize_t>(scan.phase.size());
    WriteVector<uint8>(dataGid, ebsdlib::H5OINA::BandContrast, {pointCount}, scan.bandContrast);
    WriteVector<uint8>(dataGid, ebsdlib::H5OINA::BandSlope, {pointCount}, scan.bandSlope);
    if(!scan.omitBandsDataset)
    {
      WriteVector<uint8>(dataGid, ebsdlib::H5OINA::Bands, {pointCount}, scan.bands);
    }
    WriteVector<uint8>(dataGid, ebsdlib::H5OINA::Error, {pointCount}, scan.error);
    WriteVector<float32>(dataGid, ebsdlib::H5OINA::Euler, {pointCount, 3}, scan.euler);
    WriteVector<float32>(dataGid, ebsdlib::H5OINA::MeanAngularDeviation, {pointCount}, scan.mad);
    WriteVector<uint8>(dataGid, ebsdlib::H5OINA::Phase, {pointCount}, scan.phase);
    WriteVector<float32>(dataGid, ebsdlib::H5OINA::X, {pointCount}, scan.x);
    WriteVector<float32>(dataGid, ebsdlib::H5OINA::Y, {pointCount}, scan.y);
    REQUIRE(H5Gclose(dataGid) >= 0);
  }

  REQUIRE(H5Fclose(fileId) >= 0);
  return filePath;
}

